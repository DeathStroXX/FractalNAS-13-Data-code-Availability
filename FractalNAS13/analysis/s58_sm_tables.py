"""Generate the tables that belong to the supplement.

Two kinds:

  the search space      written directly from `surrogate.SS`, which is the single definition of
                        the grid every other script uses, so the table cannot drift from the
                        encoding;
  the supplement copies of three main-paper tables, which the supplement repeats in full. These
                        are the source table verbatim with their own \\label, because a LaTeX
                        label lives in one document and the main paper's "Supplementary
                        Table~Sn" pointers have to resolve inside the supplement.

The policy table is not copied: the main paper reports those policies as differences and the
supplement reports their absolute levels, so s26_search_value.py writes both tables itself.

Run after the scripts that write the main tables.

    python3 analysis/s58_sm_tables.py
"""
import os
import re

import common
from surrogate import SS

TAB = os.path.join(common.HERE, '..', 'tables')

#: source table -> (supplement label, the label it carries in the main paper)
COPIES = {'tab_gate.tex': ('tab:sm_gate', 'tab:gate'),
          'tab_extension.tex': ('tab:sm_extension', 'tab:extension'),
          'tab_space.tex': ('tab:sm_spacetab', 'tab:space')}

HEADER = ('%% Generated by analysis/s58_sm_tables.py from %s -- do not edit.\n'
          '%% The supplement needs its own label so that the main paper\'s "Supplementary\n'
          '%% Table" pointers resolve; everything else is the source table verbatim.\n')

GROUPS = [('Structural depth', ['n_columns', 'n_blocks']),
          ('Channel width', ['base_channels']),
          ('Regularization', ['dropout_prob', 'fc_dropout']),
          ('Optimization', ['lr', 'momentum']),
          ('Categorical', ['activation', 'kernel_size', 'pooling_type', 'conv_type',
                           'norm_type', 'optimizer_type'])]
NICE = {'n_columns': '$n\\_columns$', 'n_blocks': '$n\\_blocks$',
        'base_channels': '$base\\_channels$', 'dropout_prob': '$dropout$',
        'fc_dropout': '$fc\\_dropout$', 'lr': '$lr$', 'momentum': '$momentum$',
        'activation': 'Activation', 'kernel_size': 'Kernel size', 'pooling_type': 'Pooling',
        'conv_type': 'Convolution', 'norm_type': 'Normalization',
        'optimizer_type': 'Optimizer'}


def _values(g):
    v = SS[g]
    if isinstance(v[0], str):
        return ', '.join(v)
    return '$\\{' + ', '.join(('%g' % x) for x in v) + '\\}$'


def search_space():
    n = 1
    for g in SS:
        n *= len(SS[g])
    L = [r'\begin{table}[t]', r'\centering',
         r'\caption{The FractalNet search space: 13 genes, '
         rf'${n/1e7:.1f}\times10^{{7}}$ points in all. This is the grid the original study'
         r' fixed and the grid FractalNAS-13 covers. Generated from'
         r' \texttt{analysis/surrogate.py}, which is the single definition every script'
         r' uses.}', r'\label{tab:sm_searchspace}',
         r'\footnotesize', r'\resizebox{\columnwidth}{!}{%',
         r'\begin{tabular}{l l l}', r'\toprule',
         r'\textbf{Category} & \textbf{Gene} & \textbf{Values} \\', r'\midrule']
    for cat, genes in GROUPS:
        for i, g in enumerate(genes):
            head = (rf'\multirow{{{len(genes)}}}{{*}}{{{cat}}}' if len(genes) > 1 and i == 0
                    else ('' if len(genes) > 1 else cat))
            L.append(f'{head} & {NICE[g]} & {_values(g)} ' + r'\\')
    L += [r'\bottomrule', r'\end{tabular}}', r'\end{table}']
    path = os.path.join(TAB, 'tab_searchspace.tex')
    open(path, 'w').write('\n'.join(L) + '\n')
    return path, n


def copies():
    made = []
    for src, (sm_label, main_label) in COPIES.items():
        path = os.path.join(TAB, src)
        if not os.path.exists(path):
            print(f'  skipped {src}: not generated yet')
            continue
        body = open(path).read()
        if r'\label{%s}' % main_label not in body:
            print(f'  WARNING {src}: expected \\label{{{main_label}}}; copy keeps its label')
        body = body.replace(r'\label{%s}' % main_label, r'\label{%s}' % sm_label)
        # a copy must not carry a \ref to a main-paper label, which does not exist here
        body = re.sub(r'Table~\\ref\{tab:tests\}', 'the main paper\'s test table', body)
        body = re.sub(r'Table~\\ref\{tab:settings\}', 'the main paper\'s settings table', body)
        out = os.path.join(TAB, src.replace('.tex', '_sm.tex'))
        open(out, 'w').write(HEADER % src + body)
        made.append(out)
    return made


def main():
    path, n = search_space()
    print(f'wrote {os.path.relpath(path, os.path.join(common.HERE, ".."))} '
          f'({n:,} points in the grid)')
    for p in copies():
        print(f'wrote {os.path.relpath(p, os.path.join(common.HERE, ".."))}')


if __name__ == '__main__':
    main()
